"""Generate static register names without a serial port or controller instance.

Run with the minimum supported rustypot release:
    uv run --no-project --with rustypot==1.11.0 scripts/generate_motor_registers.py
"""

import argparse
from difflib import unified_diff
from importlib.metadata import version
from pathlib import Path

import rustypot

DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / "src/lerobot/motors/registers.py"


def generate_source() -> str:
    """Return types from the register names in rustypot's exported controllers."""
    names: set[str] = set()
    for controller in vars(rustypot).values():
        registers = getattr(controller, "registers", None)
        if (
            isinstance(controller, type)
            and callable(registers)
            and callable(getattr(controller, "models", None))
        ):
            for register in registers():
                name = register.name
                names.update((name.lower(), name.upper(), name.title()))
    if not names:
        raise RuntimeError("rustypot exports no controller register names")

    rustypot_version = version("rustypot")
    license_header = Path(__file__).read_text().split('"""', maxsplit=1)[0]
    entries = "".join(f'    "{name}",\n' for name in sorted(names))
    return (
        license_header
        + f'''"""Register-name types generated from rustypot {rustypot_version}.

Do not edit this file. Regenerate it with:
    uv run --no-project --with rustypot=={rustypot_version} scripts/generate_motor_registers.py
"""

from typing import Literal, NewType

type RegisterName = Literal[
{entries}]

CustomRegister = NewType("CustomRegister", str)
"""An explicit register name for custom, dynamic, or arbitrary-case access.

This type leaves the string unchanged at runtime and skips static name checks.
RegisterName accepts lowercase, uppercase, and title-case names.
"""

type Register = RegisterName | CustomRegister
'''
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check that the output is current.")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="Path to the generated module.")
    args = parser.parse_args()
    source = generate_source()
    if args.check:
        current = args.output.read_text() if args.output.exists() else ""
        if current == source:
            return 0
        print(
            "".join(
                unified_diff(
                    current.splitlines(keepends=True),
                    source.splitlines(keepends=True),
                    fromfile=str(args.output),
                    tofile="generated register types",
                )
            ),
            end="",
        )
        return 1
    args.output.write_text(source)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
