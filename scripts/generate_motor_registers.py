"""Generate `src/lerobot/motors/registers.py` from rustypot's servo definitions.

The generated file holds a `RegisterName` literal of every register name rustypot knows,
in the three spellings `SerialMotorsBus` accepts (rustypot matches register names without
case): the definitions' own lowercase spelling, `Title_Case` and `UPPERCASE`. Typing a
register argument with it lets mypy catch a typo before the program reaches the hardware;
`CustomRegister` (in `lerobot.motors`) skips the check for names read from configuration.

Usage:

```sh
uv run --no-project --with "rustypot>=1.13.1,<2.0.0" python scripts/generate_motor_registers.py
```

`--check` regenerates in memory and exits 1 if the committed file differs.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from rustypot import ServoDefinition

# One probe name per servo definition rustypot ships. `rustypot.find_model` matches without
# case, hyphens or underscores, so any spelling of the family finds its definition. A
# definition that stops resolving, or a new one rustypot adds, needs this table revisited:
# the checks in tests/motors/test_registers.py fail loudly on both.
FAMILY_PROBES: tuple[str, ...] = (
    "ax-12w",  # AX
    "mx-28",  # MX
    "xl-320",  # XL320
    "xl330-m077",  # XL330 (covers XC330)
    "xl430-w250",  # XL430 (covers XM, XC430, XH540)
    "scs0009",  # SCS0009
    "scs0043",  # SCS0043
    "sts3215",  # STS3215 (covers STS3036, STS3250)
    "orbita2d-foc",
    "orbita2d-poulpe",
    "orbita3d-foc",
    "orbita3d-poulpe",
)

REGISTER_MODULE = Path(__file__).parents[1] / "src" / "lerobot" / "motors" / "registers.py"


def find_servo(name: str) -> ServoDefinition:
    """The rustypot definition of the servo family `name` belongs to."""
    import rustypot

    if (found := rustypot.find_model(name)) is None:
        raise RuntimeError(f"rustypot has no servo '{name}': update FAMILY_PROBES.")
    return found[1]


def collect_register_names() -> list[str]:
    """Every register name rustypot knows, lowercase and sorted."""
    names: set[str] = set()
    for probe in FAMILY_PROBES:
        names |= {register.name.lower() for register in find_servo(probe).registers()}
    return sorted(names)


def spellings(name: str) -> tuple[str, str, str]:
    """The lowercase, `Title_Case` and `UPPERCASE` spellings of a lowercase register name."""
    return name, "_".join(part.capitalize() for part in name.split("_")), name.upper()


def render_module(names: list[str]) -> str:
    """The full source of `registers.py` for `names`."""
    lines = [
        "#!/usr/bin/env python",
        "",
        "# Copyright 2026 The HuggingFace Inc. team. All rights reserved.",
        "#",
        '# Licensed under the Apache License, Version 2.0 (the "License");',
        "# you may not use this file except in compliance with the License.",
        "# You may obtain a copy of the License at",
        "#",
        "#     http://www.apache.org/licenses/LICENSE-2.0",
        "#",
        "# Unless required by applicable law or agreed to in writing, software",
        '# distributed under the License is distributed on an "AS IS" BASIS,',
        "# WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.",
        "# See the License for the specific language governing permissions and",
        "# limitations under the License.",
        "",
        "# Generated by scripts/generate_motor_registers.py from rustypot's servo definitions.",
        "# Do not edit by hand: regenerate with",
        "#",
        '#   uv run --no-project --with "rustypot>=1.13.1,<2.0.0" \\',
        "#       python scripts/generate_motor_registers.py",
        "",
        "from typing import Literal",
        "",
        "# Every register name rustypot knows, in the three spellings the bus accepts (rustypot",
        "# matches register names without case): the definitions' own lowercase spelling,",
        "# Title_Case and UPPERCASE. For a name that only exists at run time, e.g. read from a",
        "# configuration file, wrap it in `CustomRegister` (lerobot.motors) to skip the static",
        "# check.",
        "RegisterName = Literal[",
    ]
    for name in names:
        for spelling in spellings(name):
            lines.append(f'    "{spelling}",')
    lines.append("]")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the committed registers.py differs from a fresh generation",
    )
    args = parser.parse_args()

    source = render_module(collect_register_names())
    if args.check:
        if REGISTER_MODULE.read_text() == source:
            print(f"{REGISTER_MODULE} is up to date.")
            return 0
        print(f"{REGISTER_MODULE} is stale: regenerate it.", file=sys.stderr)
        return 1

    REGISTER_MODULE.write_text(source)
    print(f"Wrote {REGISTER_MODULE}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
