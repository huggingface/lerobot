import logging
from typing import Any

from lerobot.utils.decorators import check_if_already_connected, check_if_not_connected

logger = logging.getLogger(__name__)


class BimanualMixin:
    """Lifecycle delegation for bimanual robots and teleoperators.

    Concrete subclasses must populate ``self.left_arm`` and ``self.right_arm`` in
    their own ``__init__``. They retain ownership of feature dicts and the
    data-routing methods (``get_action`` / ``send_action`` / ``get_observation`` /
    ``send_feedback``), which vary per-embodiment.

    Inherit before the ``Robot`` / ``Teleoperator`` base so the mixin's methods
    take precedence in the MRO::

        class BiFooFollower(BimanualMixin, Robot): ...
    """

    left_arm: Any
    right_arm: Any

    @property
    def is_connected(self) -> bool:
        return self.left_arm.is_connected and self.right_arm.is_connected

    @property
    def is_calibrated(self) -> bool:
        return self.left_arm.is_calibrated and self.right_arm.is_calibrated

    @check_if_already_connected
    def connect(self, calibrate: bool = True) -> None:
        self.left_arm.connect(calibrate)
        self.right_arm.connect(calibrate)

    def calibrate(self) -> None:
        self.left_arm.calibrate()
        self.right_arm.calibrate()

    def configure(self) -> None:
        self.left_arm.configure()
        self.right_arm.configure()

    @check_if_not_connected
    def disconnect(self) -> None:
        """Attempt cleanup of both arms, then re-raise the first failure.

        Cleanup continues after errors or interrupts. Additional failures are logged.

        Raises:
            BaseException: The first cleanup failure, after both arms have been attempted.
        """
        first_exception: BaseException | None = None
        for name, arm in (("left", self.left_arm), ("right", self.right_arm)):
            try:
                arm.disconnect()
            except BaseException as e:
                logger.error(f"Failed to disconnect {name} arm: {e}")
                if first_exception is None:
                    first_exception = e

        if first_exception is not None:
            raise first_exception
